class Command(BaseCommand):
    help = 'Load sample food and exercise recommendations.'

    def handle(self, *args, **options):
        FoodItem.objects.all().delete()
        ExerciseItem.objects.all().delete()

        for item in [*FOODS, *ADDITIONAL_FOODS]:
            food_data = {
                **item,
                'food_category': item.get('food_category') or _food_category(item),
            }
            FoodItem.objects.create(**food_data)
        for item in [*EXERCISES, *ADDITIONAL_EXERCISES]:
            exercise_data = {
                **item,
                'location': item.get('location') or _exercise_location(item),
            }
            ExerciseItem.objects.create(**exercise_data)

        self.stdout.write(self.style.SUCCESS(
            f'Seeded {len(FOODS) + len(ADDITIONAL_FOODS)} foods and '
            f'{len(EXERCISES) + len(ADDITIONAL_EXERCISES)} exercises.'
        ))


def _food_category(item):
    text = ' '.join((item['name'], item['description'], item.get('ingredients', ''))).casefold()
    groups = {
        FoodCategory.FRUIT: ('fruit', 'banana', 'mango', 'papaya', 'apple', 'berries', 'berry', 'avocado'),
        FoodCategory.VEGETABLE: ('vegetable', 'spinach', 'cucumber', 'tomato', 'salad', 'leafy', 'carrot', 'cabbage'),
        FoodCategory.GRAIN: ('oat', 'rice', 'bread', 'toast', 'corn', 'whole grain'),
        FoodCategory.PROTEIN: ('chicken', 'fish', 'egg', 'tofu', 'lentil', 'bean', 'tuna', 'meat', 'nut'),
        FoodCategory.DAIRY: ('milk', 'yogurt', 'dairy', 'cheese'),
    }
    matches = [
        category
        for category, keywords in groups.items()
        if any(keyword in text for keyword in keywords)
    ]
    if len(matches) > 1:
        return FoodCategory.MIXED
    return matches[0] if matches else FoodCategory.OTHER


def _exercise_location(item):
    name = item['name'].casefold()
    if any(keyword in name for keyword in ('indoor', 'seated', 'chair', 'wall', 'stationary')):
        return ExerciseLocation.INDOOR
    if 'outdoor' in name:
        return ExerciseLocation.OUTDOOR
    return ExerciseLocation.BOTH
